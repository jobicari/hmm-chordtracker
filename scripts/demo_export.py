"""Prepare samples for the demo website (demo/): audio plus the chords the live chain gives for it.

    python scripts/demo_export.py 00_Funk2-108-Eb_comp 00_Rock3-148-C_comp 00_SS3-98-C_comp
    python scripts/demo_export.py --model v7_2 ...      # V7.2's 24-class network instead

Each argument is a GuitarSet validation take (splits/guitarset.json); test takes are refused, as for
every figure in the repo. For each take this runs the live chain the demo server runs (Analyzer, a
play_along.Analysis fed the take block by block as 16-bit PCM, as the page streams it), so the prepared
labels are the live ones frame for frame. The model (demo.MODELS):

    v14 (default)   V14's network with an N class (results/v14/n_seed0, configs/v14.yaml: 61 classes,
                    vocabulary A and N) at its best decoder setting on validation (N weight x0.1, chord
                    -> N rate x0.5, play_along.load_chain); N comes from the network, silence gate off
    v7_2            V7.2's network (results/v7_2/c2_la2_seed0: 24 classes, major and minor) with the
                    silence gate (N where the input stays below play_along.SILENCE_DBFS for 3 frames)

The tuning seconds start at the first frame at or above play_along.SILENCE_DBFS for both. It writes,
under demo/samples/ (git-ignored, regenerated by this script):

    <take>.wav          the GuitarSet mono mic recording, copied unchanged (CC BY 4.0)
    <take>.json         the segments of the three operating points and of the network alone, the GuitarSet
                        annotation, metadata (chordtracker.demo)
    index.json          every sample in the folder, for the page's picker

Then: python -m http.server -d demo 8000, and open http://localhost:8000.
"""
import argparse
import json
import shutil
import sys
from pathlib import Path

import librosa
import numpy as np
import soundfile as sf

from chordtracker import data_v5, demo, features_v7_1, model_v6, paths, train_v7_2
from chordtracker.data_v5 import CENTRE_ROW, PATCH_BINS, PATCH_FRAMES
from chordtracker.learned_emission import LABELS
from chordtracker.play_along import CLASS_LABELS, INPUT_LOOKAHEAD, SILENCE_DBFS, SILENCE_FRAMES, V14_N_WEIGHT, \
    V14_RATE_FACTOR, Analysis, load_chain

sys.path.insert(0, str(Path(__file__).parent))
import run_v5  # noqa: E402
import run_v7_2  # noqa: E402

OUT = paths.REPO_ROOT / "demo" / "samples"
FEATURE = "causal log-CQT (harmonic part, C2 grid), computed as the live chain does"
DEFAULT_SILENCE_DBFS = {"v14": -np.inf, "v7_2": SILENCE_DBFS}     # the gate per model: off for v14's own N
REFERENCE_SOURCE = ("GuitarSet lead-sheet chords for this take (the first chord annotation of its JAMS "
                    "file, the reference all of the project's scores use)")
SOURCE = {"dataset": "GuitarSet", "split": "validation", "license": "CC BY 4.0",
          "url": "https://guitarset.weebly.com/"}


def take_of(song_id: str) -> data_v5.Take:
    for take in data_v5.guitarset_takes("val"):
        if take.key == f"guitarset/{song_id}":
            return take
    raise SystemExit(f"{song_id} is not a GuitarSet validation take (splits/guitarset.json)")


def title_of(song_id: str) -> str:
    """"00_Funk2-108-Eb_comp" -> "GuitarSet player 00 - Funk 2, 108 bpm, Eb (comping)"."""
    player, rest = song_id.split("_", 1)
    style, bpm, key = rest.removesuffix("_comp").split("-")
    name = style.rstrip("0123456789")
    return f"GuitarSet player {player} - {name} {style[len(name):]}, {bpm} bpm, {key} (comping)"


def pipeline_settings(analyzer: "Analyzer", silence_dbfs: float) -> dict:
    """The settings of every stage, read from the run's config, the code's constants and the files used.

    silence_dbfs: the silence gate's level (-inf: no gate, reported as None).
    """
    cfg, run = analyzer.cfg, analyzer.run
    q, a = cfg["cqt"], cfg["audio"]
    semitone_bins = q["bins_per_octave"] // 12
    lowest = librosa.note_to_midi(q["fmin"]) + CENTRE_ROW // semitone_bins
    counts = json.loads((paths.REPO_ROOT / cfg["transitions"]["counts"]).read_text())
    classes = len(analyzer.labels) - (0 if analyzer.learned_n else 1)          # the network's outputs
    n_knobs = {"noChordWeight": V14_N_WEIGHT, "noChordRateFactor": V14_RATE_FACTOR} if analyzer.learned_n else {}
    return {
        "sampleRate": a["sr"],
        "harmonic": {"nFft": features_v7_1.N_FFT, "stftHop": features_v7_1.STFT_HOP,
                     "medianFrames": a.get("harmonic_median_frames", features_v7_1.MEDIAN_FRAMES),
                     "margin": a["harmonic_margin"], "lookaheadFrames": features_v7_1.LOOKAHEAD_FRAMES},
        "cqt": {"hop": q["hop_length"], "binsPerOctave": q["bins_per_octave"], "nBins": q["n_bins"],
                "tuningSeconds": q["tuning_seconds"], "tuningOnsetDbfs": SILENCE_DBFS, "networkBins": PATCH_BINS,
                "networkLowest": librosa.midi_to_note(lowest, unicode=False),
                "networkHighest": librosa.midi_to_note(lowest + PATCH_BINS // semitone_bins - 1, unicode=False)},
        "compression": {"gamma": cfg["compression"]["gamma"], "levelPercentile": cfg["compression"]["level_percentile"]},
        "network": {"name": analyzer.name, "windowFrames": PATCH_FRAMES, "inputLookaheadFrames": INPUT_LOOKAHEAD,
                    "gruHidden": model_v6.HIDDEN, "classes": classes, "qualities": analyzer.qualities,
                    "noChordClass": analyzer.learned_n, "trainedOn": analyzer.trained_on,
                    "model": str(run.relative_to(paths.REPO_ROOT))},
        "hmm": {"states": classes, "changeCountsSource": counts["source"],
                "alpha": cfg["transitions"]["alpha"], "tau": cfg["transitions"]["tau"], **n_knobs},
        "silence": {"dbfs": silence_dbfs if np.isfinite(silence_dbfs) else None, "frames": SILENCE_FRAMES},
    }


class Analyzer:
    """A model's live chain, loaded once (demo.MODELS): new sessions for the server, and audio file -> the
    JSON of chordtracker.demo.result for the export.

    labels: the Harte label of every index, "N" last (the network's own class for v14, the gate's for v7_2);
    qualities: the chord qualities of the vocabulary, for the page.
    """

    def __init__(self, model: str = demo.DEFAULT_MODEL):
        if model not in demo.MODELS:
            raise ValueError(f"unknown model {model!r}: one of {sorted(demo.MODELS)}")
        self.name, self.points, self.learned_n = model, demo.MODELS[model], model == "v14"
        if model == "v14":
            self.cfg = run_v5.load_config(paths.REPO_ROOT / "configs" / "v14.yaml")
            self.run = paths.REPO_ROOT / "results" / "v14" / "n_seed0"
            self.model, self.prior, self.Q = load_chain("v14", self.cfg, self.run)
            self.labels, self.qualities = CLASS_LABELS + ["N"], ["maj", "min", "7", "maj7", "min7"]
            self.trained_on = "the RWC Popular Music, GuitarSet and ChoCo training songs"
        else:
            base = run_v5.load_config(paths.REPO_ROOT / "configs" / "v7_2.yaml")
            self.cfg = run_v7_2.cell_config(base, "C2", INPUT_LOOKAHEAD, 0)
            self.run = run_v7_2.run_dir("C2", INPUT_LOOKAHEAD, 0)
            self.model = train_v7_2.load(self.run / "model.pt", False, 0.5).cpu()
            self.prior = np.array(json.loads((self.run / "prior.json").read_text()))
            self.Q = run_v5.change_prior(self.cfg)
            self.labels, self.qualities = list(LABELS) + ["N"], ["maj", "min"]
            self.trained_on = "the RWC Popular Music and GuitarSet training takes"
        self.sr, self.hop = self.cfg["audio"]["sr"], self.cfg["cqt"]["hop_length"]

    def session(self, silence_dbfs: float) -> Analysis:
        """A fresh live session: the gate at silence_dbfs (-inf: off), the tuning from the first audible frame."""
        gate = silence_dbfs if np.isfinite(silence_dbfs) else None
        return Analysis(self.cfg, self.model, self.prior, self.Q, self.points, gate, len(self.labels) - 1, SILENCE_DBFS)

    def analyze(self, audio_path: Path, sample_id: str, title: str, audio: str | None, reference=None,
                reference_source: str | None = None, source: dict | None = None,
                silence_dbfs: float | None = None) -> dict:
        """The sample's JSON: the session fed the file as the page streams it (16-bit PCM), then finished."""
        silence_dbfs = DEFAULT_SILENCE_DBFS[self.name] if silence_dbfs is None else silence_dbfs
        duration = sf.info(str(audio_path)).duration
        y, _ = librosa.load(str(audio_path), sr=self.sr, mono=True)
        pcm = np.clip(np.round(y * 32767), -32768, 32767).astype(np.float32) / 32768.0
        session = self.session(silence_dbfs)
        for i in range(0, len(pcm), self.hop):
            session.step(pcm[i:i + self.hop])
        session.finish()
        points = {p: np.array(labels) for p, labels in session.labels.items()}
        metadata = {"sampleRate": self.sr, "hopLength": self.hop, "featureName": FEATURE,
                    "model": str(self.run.relative_to(paths.REPO_ROOT)),
                    "inputLookaheadFrames": INPUT_LOOKAHEAD, "pipeline": pipeline_settings(self, silence_dbfs)}
        return demo.result(sample_id, title, audio, duration, points, points[demo.FRAMEWISE_POINT], self.labels,
                           reference, reference_source, source or {}, metadata, self.points)


def export(song_id: str, analyzer: Analyzer) -> dict:
    take = take_of(song_id)
    audio = f"{song_id}.wav"
    OUT.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(take.audio, OUT / audio)
    out = analyzer.analyze(take.audio, song_id, title_of(song_id), audio, take.annotation, REFERENCE_SOURCE, SOURCE)
    (OUT / f"{song_id}.json").write_text(json.dumps(out, indent=1))
    return out


def write_index() -> None:
    rows = []
    for file in sorted(OUT.glob("*.json")):
        if file.name == "index.json":
            continue
        s = json.loads(file.read_text())
        rows.append({"id": s["id"], "title": s["title"], "file": file.name})
    (OUT / "index.json").write_text(json.dumps({"samples": rows}, indent=1))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("takes", nargs="+", help="GuitarSet validation take ids, e.g. 00_Funk2-108-Eb_comp")
    parser.add_argument("--model", choices=sorted(demo.MODELS), default=demo.DEFAULT_MODEL)
    args = parser.parse_args()
    analyzer = Analyzer(args.model)
    for song_id in args.takes:
        s = export(song_id, analyzer)
        print(song_id, f"{s['duration']} s,", ", ".join(f"{p['id']}: {len(p['segments'])} segments" for p in s["points"]),
              flush=True)
    write_index()


if __name__ == "__main__":
    main()
